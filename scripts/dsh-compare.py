#!/usr/bin/env python3
"""Run ordinary DSH coding sessions for prose comparisons; no scoring or DB ingestion."""
from __future__ import annotations

import argparse
import copy
from dataclasses import asdict
import json
import os
import re
from pathlib import Path
import subprocess
import sys
import tempfile
import uuid

import yaml


class Js(str):
    """Preserve Cordis expressions without evaluating configuration in Python."""


class Loader(yaml.SafeLoader):
    pass


class Dumper(yaml.SafeDumper):
    pass


# Cordis uses YAML 1.2: the effort key "off" is a string, not YAML 1.1 false.
Loader.yaml_implicit_resolvers = {
    key: [(tag, pattern) for tag, pattern in values if tag != 'tag:yaml.org,2002:bool']
    for key, values in Loader.yaml_implicit_resolvers.items()
}
Loader.add_implicit_resolver('tag:yaml.org,2002:bool', re.compile(r'^(?:true|false)$', re.I), list('tTfF'))
Loader.add_constructor('tag:yaml.org,2002:js', lambda loader, node: Js(loader.construct_scalar(node)))
Dumper.add_representer(Js, lambda dumper, value: dumper.represent_scalar('tag:yaml.org,2002:js', str(value)))


def read_yaml(path):
    return yaml.load(Path(path).read_text(), Loader=Loader)


def write_yaml(path, value):
    Path(path).write_text(yaml.dump(value, Dumper=Dumper, sort_keys=False))


def standard_patch(runtime, web_patch):
    """Materialize the shipped standard agent plane in the SDK's host plane."""
    bundle = runtime / 'packages/bundle'
    base = read_yaml(bundle / 'base/cordis.patch.yml')[0]['insert']
    base_ids = {row['id'] for row in base}
    standard = read_yaml(bundle / 'web-app/presets/standard.patch.yml')[0]['insert'][0]['config']['plugins']
    web = read_yaml(bundle / 'web-app/cordis.patch.yml')
    patch = [copy.deepcopy(row) for row in web
             if row.get('id') in base_ids and row.get('disabled') is True]
    # SDK agents use the global layer: translate the scope-only persona row.
    persona = next(row['config'] for row in standard if row['id'] == 'persona')
    patch.append({'id': 'system-prompt', 'config': {
        'personaPrefix': persona['prefix'], 'personaSuffix': persona.get('suffix', '')}})
    for row in standard:
        if row['id'] == 'persona':
            continue
        row = copy.deepcopy(row)
        if row['id'] == 'delegation':
            # Standing Web preset settings require an agent-scoped preset realm.
            # SDK children keep normal explicit model selection/inheritance instead.
            for child in row['config']:
                child.get('config', {}).pop('modelSelectionSettings', None)
        if row['id'] in base_ids:
            row.setdefault('disabled', False)
            patch.append(row)
        else:
            patch.append({'insert': [row]})
    # Preserve model routes, exact effort maps, and ordinary execution permission.
    # Other web-only UI, integrations, and customized presets are intentionally absent.
    shared = {'llm-pi-ai', 'llm-deepseek', 'agent-default-model', 'permission',
              'thinking-effort', 'web-search-deepseek'}
    patch.extend(copy.deepcopy(row) for row in web_patch if row.get('id') in shared)
    return patch


def setup(args):
    profile = args.home / 'profiles' / args.profile
    env = {**os.environ, 'DSH_HOME': str(args.home)}
    if not profile.exists():
        subprocess.run([str(args.dsh), '--profile', args.profile, '--from-default-profile', 'sdk',
                        '--dump-default-config'], env=env, stdout=subprocess.DEVNULL, check=True)
    manifest = json.loads((profile / 'package.json').read_text())
    if '@deepseek-ai/dsh-sdk-app' not in manifest['dsh']['profile']['bundles']:
        raise ValueError('Destination must be an SDK profile')
    plugin = args.home / 'profiles/web/node_modules/@hytime/dsh-thinking-effort/package.json'
    version = json.loads(plugin.read_text())['version']
    if manifest.get('dependencies', {}).get('@hytime/dsh-thinking-effort') != version:
        subprocess.run([str(args.dsh), 'plugin', '--profile', args.profile, 'add',
                        f'@hytime/dsh-thinking-effort@{version}'], env=env, check=True)
    target = profile / 'cordis.patch.yml'
    marker = '# Generated by goblinbench scripts/dsh-compare.py\n'
    existing = target.read_text() if target.exists() else ''
    if existing.strip() and not existing.startswith(marker):
        # The launcher initializes an empty patch list, optionally with comments.
        if read_yaml(target) not in (None, []):
            raise ValueError(f'Refusing to overwrite a user-edited profile: {target}')
    patch = standard_patch(args.runtime, read_yaml(args.home / 'profiles/web/cordis.patch.yml'))
    target.write_text(marker + yaml.dump(patch, Dumper=Dumper, sort_keys=False))
    target.chmod(0o600)
    print(f'Configured {target} from web providers + shipped standard tooling + thinking-effort {version}')


def catalog(args):
    with tempfile.TemporaryDirectory(prefix='dsh-catalog-') as directory:
        root = Path(directory)
        output = root / 'catalog.json'
        patch = root / 'catalog.patch.yml'
        write_yaml(patch, [
            {'id': 'sdk-app-startup', 'disabled': True},
            {'id': 'sdk-jsonrpc-server', 'disabled': True},
            {'insert': [{'name': str(Path(__file__).parent / 'dsh-comparison/catalog.mjs')}]},
        ])
        probe = subprocess.run([str(args.dsh), '--profile', args.profile, '--patch', str(patch)],
                       env={**os.environ, 'DSH_HOME': str(args.home),
                            'DSH_COMPARISON_CATALOG': str(output)},
                       stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.PIPE,
                       text=True, check=True, timeout=60)
        if 'did not activate' in probe.stderr:
            raise RuntimeError(probe.stderr)
        if probe.stderr:
            print(probe.stderr, file=sys.stderr, end='')
        print(output.read_text())


def run(args):
    # Use the SDK matching the selected checkout, not a separately installed wheel/runtime.
    sys.path.insert(0, str(args.runtime / 'python/sdk/src'))
    from deepseek_harness import DeepSeekHarness

    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=False)
    session = args.session_id or f'comparison-{uuid.uuid4()}'
    prompt = args.prompt_file.read_text()
    prompt = ('Work in the specified repository. Follow its AGENTS.md and applicable nested '
              'instructions; read them if they are not already in your context.\n\n' + prompt)
    (output / 'prompt.txt').write_text(prompt)
    metadata = dict(session_id=session, workspace=str(args.workspace.resolve()),
                    provider=args.provider, model=args.model, effort=args.effort,
                    profile=args.profile, dsh=str(args.dsh.resolve()),
                    runtime=str(args.runtime), status='running')
    (output / 'session.json').write_text(json.dumps(metadata, indent=2) + '\n')
    try:
        with (output / 'events.jsonl').open('w') as events:
            def record(notification):
                events.write(json.dumps(asdict(notification)) + '\n')
                events.flush()

            with DeepSeekHarness(dsh_bin=str(args.dsh), dsh_home=str(args.home),
                                 profile=args.profile, cwd=str(args.workspace.resolve()),
                                 provider=args.provider, model=args.model,
                                 reasoning_effort=None if args.effort == 'default' else args.effort,
                                 request_timeout_seconds=args.timeout,
                                 env={'DSH_MAX_TOKENS_AS_SUCCESS': 'false'}) as harness:
                result = harness.run(prompt, session_id=session, on_notification=record)
            (output / 'response.md').write_text(result.final_response)
            metadata.update(status='finished', finish_reason=result.finish_reason)
            return 0 if result.finish_reason == 'completed' else 1
    except Exception as error:
        metadata.update(status='error', error=str(error))
        raise
    finally:
        (output / 'session.json').write_text(json.dumps(metadata, indent=2) + '\n')
        print(f'Session {session}: {metadata["status"]}; artifacts: {output}', file=sys.stderr)
        if args.notify_thread:
            notification = subprocess.run(['codex', 'queue', '--thread', args.notify_thread, '--message',
                f'DSH comparison session {session} ended: {metadata["status"]}, '
                f'finish_reason={metadata.get("finish_reason")}. Read {output / "session.json"} '
                f'and {output / "response.md"}, inspect the candidate work, and continue the prose comparison.'],
                capture_output=True, text=True)
            (output / 'queue.log').write_text(notification.stdout + notification.stderr)
            if notification.returncode:
                print('Completion queue failed; see queue.log', file=sys.stderr)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', type=Path, default=Path('/home/system/dsh-runtime'))
    parser.add_argument('--home', type=Path, default=Path.home() / '.dsh')
    parser.add_argument('--dsh', type=Path, help='Override CLI; normally derived from --runtime')
    parser.add_argument('--profile', default='comparison-sdk')
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('setup')
    sub.add_parser('catalog')
    run_parser = sub.add_parser('run')
    run_parser.add_argument('--workspace', required=True, type=Path)
    run_parser.add_argument('--provider', required=True)
    run_parser.add_argument('--model', required=True)
    run_parser.add_argument('--effort', required=True, help='Exact catalog effort ID, or default')
    run_parser.add_argument('--prompt-file', required=True, type=Path)
    run_parser.add_argument('--out', required=True, type=Path)
    run_parser.add_argument('--session-id', help='Reuse only to continue this candidate conversation')
    run_parser.add_argument('--timeout', type=float, default=1800)
    run_parser.add_argument('--notify-thread', help='Queue completion to this Codex task UUID')
    args = parser.parse_args()
    args.runtime = args.runtime.resolve()
    args.home = args.home.resolve()
    args.dsh = (args.dsh or args.runtime / 'apps/cli/lib/bin.js').resolve()
    return {'setup': setup, 'catalog': catalog, 'run': run}[args.command](args)


if __name__ == '__main__':
    sys.exit(main())
